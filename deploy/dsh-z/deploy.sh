log "  workspace      $MULTICA_Z_WS_SLUG = $MULTICA_Z_WORKSPACE_ID"
log "  lane web       ${WEB_URL:-http://127.0.0.1:3180/} (unit ${DSH_Z_WEB_UNIT:-manual}, multica plugin row)"
log "done"
